export interface OfflineWorkerOptions {
  /** Change this whenever any resource changes. Never reuse a version for different bytes. */
  version: string;
  /** Application-specific prefix. The worker also isolates caches by registration scope. */
  cachePrefix: string;
  resources: readonly string[];
  entrypoint?: string;
  failureMessageType?: string;
}

/** Generate a classic service worker at build time, with no runtime dependency. */
export function createOfflineWorkerSource(options: OfflineWorkerOptions): string {
  const {version, cachePrefix, resources, entrypoint = './index.html', failureMessageType = 'game-offline-error'} = options;
  if (!version || !cachePrefix || !resources.length) throw new TypeError('Version, cache prefix and resources are required.');
  const base = new URL('https://example.invalid/game/');
  const normalize = (path: string) => {
    const url = new URL(path, base);
    if (!path || path.startsWith('/') || path.includes('\\') || url.origin !== base.origin ||
        !url.pathname.startsWith(base.pathname) || url.search || url.hash || /^[a-z]+:/i.test(path)) {
      throw new TypeError('Offline resources must be relative paths inside the worker scope, without queries or fragments.');
    }
    return './' + url.pathname.slice(base.pathname.length);
  };
  const entries = [...new Set(resources.map(normalize))];
  const page = normalize(entrypoint);
  if (!entries.includes(page)) throw new TypeError('The offline entrypoint must be included in resources.');
  return `// Generated by browser-game-runtime. Activate only after a complete installation.
const RESOURCES = ${JSON.stringify(entries)};
const SCOPE = new URL(self.registration.scope);
const PREFIX = ${JSON.stringify(cachePrefix)} + encodeURIComponent(SCOPE.pathname) + '-';
const CACHE = PREFIX + ${JSON.stringify(version)};
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  try {
    for (const path of RESOURCES) await cache.add(new Request(new URL(path, SCOPE).href, {cache: 'no-store'}));
  } catch (error) {
    await caches.delete(CACHE);
    const clients = await self.clients.matchAll({type: 'window', includeUncontrolled: true});
    for (const client of clients) {
      const url = new URL(client.url);
      if (url.origin === SCOPE.origin && url.pathname.startsWith(SCOPE.pathname)) {
        client.postMessage({type: ${JSON.stringify(failureMessageType)}, name: error && error.name ? String(error.name) : 'Error'});
      }
    }
    throw error;
  }
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const key = event.request.mode === 'navigate' ? new URL(${JSON.stringify(page)}, SCOPE).href : event.request;
    return await cache.match(key) || fetch(event.request);
  })());
});
`;
}
